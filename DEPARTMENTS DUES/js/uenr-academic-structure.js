window.UENRHelpers = {
  normalizeValue(value) {
    return String(value || '')
      .trim()
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, ' ')
      .replace(/\s+/g, ' ')
      .trim();
  },
  flattenAcademicStructure() {
    const flat = [];
    for (const campus of window.UENRAcademicStructure) {
      for (const school of campus.schools) {
        for (const department of school.departments) {
          const activeProgrammes = department.programmes.filter((programme) => programme.active);
          for (const programme of activeProgrammes) {
            flat.push({
              campus: campus.campus,
              school: school.name,
              department: department.name,
              programme: programme.name,
              type: programme.name.toLowerCase().includes('diploma') ? 'Diploma' : programme.name.toLowerCase().includes('msc') || programme.name.toLowerCase().includes('mphil') || programme.name.toLowerCase().includes('phd') ? 'Postgraduate' : 'Undergraduate'
            });
          }
        }
      }
    }
    return flat;
  },
  getCampusOptions() {
    return window.UENRAcademicStructure.map((item) => item.campus);
  },
  getSchoolOptions(campusName) {
    const campus = window.UENRAcademicStructure.find((item) => this.normalizeValue(item.campus) === this.normalizeValue(campusName));
    return campus ? campus.schools.map((school) => school.name) : [];
  },
  getDepartmentOptions(campusName, schoolName) {
    const campus = window.UENRAcademicStructure.find((item) => this.normalizeValue(item.campus) === this.normalizeValue(campusName));
    if (!campus) return [];
    const school = campus.schools.find((item) => this.normalizeValue(item.name) === this.normalizeValue(schoolName));
    return school ? school.departments.map((department) => department.name) : [];
  },
  getProgrammeOptions(campusName, schoolName, departmentName) {
    const campus = window.UENRAcademicStructure.find((item) => this.normalizeValue(item.campus) === this.normalizeValue(campusName));
    if (!campus) return [];
    const school = campus.schools.find((item) => this.normalizeValue(item.name) === this.normalizeValue(schoolName));
    if (!school) return [];
    const department = school.departments.find((item) => this.normalizeValue(item.name) === this.normalizeValue(departmentName));
    if (!department) {
      const partialMatch = school.departments.find((item) => this.normalizeValue(item.name).includes(this.normalizeValue(departmentName)) || this.normalizeValue(departmentName).includes(this.normalizeValue(item.name)));
      if (!partialMatch) return [];
      return partialMatch.programmes.filter((programme) => programme.active).map((programme) => programme.name);
    }
    return department.programmes.filter((programme) => programme.active).map((programme) => programme.name);
  }
};
